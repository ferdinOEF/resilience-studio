// Embed apps/api/migrations/*.sql into src/migrations.ts so the admin bootstrap route can apply them on Vercel (no file system there).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), "utf8"))} }`).join(",\n");
writeFileSync(join(here, "..", "src", "migrations.ts"), `// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log(`embedded ${files.length} migrations`);
