"""
Regenerate docs/CITATIONS.md from the data files, so the living citation
document can never drift from what the tool actually uses.

Usage:  python packages/core/tools/build_citations_md.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "src" / "data"
cit = json.loads((D / "citations.json").read_text(encoding="utf-8"))["citations"]
sol = json.loads((D / "solutions.json").read_text(encoding="utf-8"))
haz = json.loads((D / "hazards.json").read_text(encoding="utf-8"))

PROV = {"prior_project": "carried from prior project", "build_spec": "named in build spec", "this_pass": "**added this pass: to verify against source**", "checked_this_pass": "checked against the source document"}
TAG = {"solid_direct": "solid_direct", "reasoned_extrapolation": "reasoned_extrapolation", "placeholder_needs_calibration": "**placeholder_needs_calibration**"}


def rng(p):
    return f"{p['value']} ({p['low']}–{p['high']})" if "low" in p else f"{p['value']}"


out = [
    "# CITATIONS",
    "",
    "_Generated by `python packages/core/tools/build_citations_md.py` from `packages/core/src/data/*.json`. Do not edit by hand._",
    "",
    "The professional-tool counterpart of the Khazan project's hazard-citation notes, kept in the repository so it ships with the code.",
    "Every numeric parameter the model uses is listed with its grounding-quality tag and sources.",
    "",
    "## Solution parameters",
    "",
    "| Solution | Parameter | Value (range) | Unit | Grounding | Sources |",
    "|---|---|---|---|---|---|",
]
for s in sol["solutions"]:
    for e in s["effects"]:
        for k, p in e["params"].items():
            srcs = "; ".join(cit[c]["short"] for c in p.get("citations", [])) or "–"
            out.append(f"| {s['name']} | {p['label']} | {rng(p)} | {p['unit']} | {TAG[p['grounding']]} | {srcs} |")
    for d in s["instanceParams"]:
        out.append(f"| {s['name']} | {d['label']} (per placement, default) | {d['default']} | {d['unit']} | {TAG[d['grounding']]} | – |")

out += ["", "## Hazard and model parameters", "", "| Parameter | Value | Unit | Grounding | Sources | What resolves it |", "|---|---|---|---|---|---|"]
for k, p in haz["params"].items():
    srcs = "; ".join(cit[c]["short"] for c in p.get("citations", [])) or "–"
    out.append(f"| {p['label']} | {p['value']} | {p['unit']} | {TAG[p['grounding']]} | {srcs} | {p['note']} |")

out += ["", "## References", ""]
for cid in sorted(cit, key=lambda c: cit[c]["short"]):
    c = cit[cid]
    out.append(f"- **{c['short']}** (`{cid}`, {PROV[c['provenance']]}). {c['full']}  \n  _Used for:_ {c['usedFor']}")

(ROOT.parent.parent / "docs" / "CITATIONS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote docs/CITATIONS.md")
